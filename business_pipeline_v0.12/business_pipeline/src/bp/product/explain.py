TEMPLATE_METHODS = frozenset({"case_decision"})

#: Calculator tools whose catalogue notes do not yet carry a formula/step list.
#: The explainer names the gap instead of inventing a derivation; adding the
#: notes removes the tool from this set and is a content-only change.
NOTES_GAPS = frozenset({
    "factorial", "kruskal_wallis", "logit", "mann_whitney", "multicomp",
    "onesample", "paired", "posthoc", "spearman", "weighted",
})


def coverage():
    """What the explainer can teach today, without inventing anything.

    Returns three lists: tools with formula and steps, tools with a contract
    only, and tools with neither.  It is a report, not a gate; the guard test
    uses `NOTES_GAPS` to keep the gap from growing silently.
    """
    ready, partial, missing = [], [], []
    for key, info in subjects.TOOL_INFO.items():
        notes = subjects.STUDENT_NOTES.get(key) or {}
        if notes.get("formula") and notes.get("steps"):
            ready.append(key)
        elif _contract(info.get("method")):
            partial.append(key)
        else:
            missing.append(key)
    return {"ready": sorted(ready), "partial": sorted(partial), "missing": sorted(missing),
            "declared_gaps": sorted(NOTES_GAPS)}


# --- small helpers ----------------------------------------------------------

def slug(title, fallback="paper"):
    """A safe file stem: lowercase, hyphens, no path characters, capped."""
    base = re.sub(r"[^a-z0-9]+", "-", str(title or "").lower()).strip("-")
    return (base[:60].strip("-") or fallback)


def _text(value):
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        return ", ".join(_text(item) for item in value)
    if isinstance(value, dict):
        try:
            return json.dumps(value, sort_keys=True, ensure_ascii=False)
        except (TypeError, ValueError):
            return str(value)
    return str(value)


def _lines(value):
    """A stored string or list of strings as a list of lines."""
    if value is None:
        return []
    if isinstance(value, str):
        return value.splitlines()
    if isinstance(value, (list, tuple)):
        return [_text(item) for item in value]
    return [_text(value)]


def _contract(method):
    return CONTRACTS.get(method) or {}


def _tool_for(method, inputs=None):
    """The catalogue tool whose teaching notes belong to this method."""
    candidates = [(key, info) for key, info in subjects.TOOL_INFO.items()
                  if info.get("method") == method]
    if not candidates:
        return None, None
    timing = str((inputs or {}).get("timing") or "").lower()
    if timing == "mid":
        for key, info in candidates:
            if key == "dcfmid":
                return key, info
    for key, info in candidates:
        if key == method:
            return key, info
    return candidates[0]


def _notes(method, inputs=None):
    key, info = _tool_for(method, inputs)
    notes = subjects.STUDENT_NOTES.get(key or "", {}) if key else {}
    return key, info, notes


def _humanise(name):
    return str(name or "").replace("_", " ").strip().capitalize()


def _sentence_list(items):
    items = [str(item) for item in items if str(item or "").strip()]
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + " and " + items[-1]


def _q(label, answer):
    return {"question": label, "answer": answer}


def _section(heading, paragraphs=None, bullets=None, table=None, level=1):
    entry = {"heading": heading, "level": level}
    if paragraphs:
        entry["paragraphs"] = [str(p) for p in paragraphs if str(p or "").strip()]
    if bullets:
        entry["bullets"] = [str(b) for b in bullets if str(b or "").strip()]
    if table:
        entry["table"] = table
    return entry


def _table(columns, rows):
    return {"columns": [str(c) for c in columns],
            "rows": [[_text(c) for c in row] for row in rows]}


def _record(bundle):
    """The provenance fields a case bundle records; no new values."""
    appendix = ((bundle.get("delivery") or {}).get("appendix") or {})
    reperform = bundle.get("reperform") or {}
    return {
        "case_id": bundle.get("id"),
        "created_at": bundle.get("created_at"),
        "method": (reperform.get("method") or {}).get("id") or (appendix.get("method") or {}).get("id"),
        "method_version": (reperform.get("method") or {}).get("version")
                          or (appendix.get("method") or {}).get("version"),
        "tier": appendix.get("tier") or bundle.get("tier"),
        "spec_hash": appendix.get("spec_hash") or bundle.get("spec_hash"),
        "outputs_hash": reperform.get("outputs_hash") or bundle.get("outputs_hash"),
        "code_hash": appendix.get("code_hash"),
        "env_hash": appendix.get("env_hash") or reperform.get("env_hash"),
        "run_id": appendix.get("run_id"),
        "sandbox": appendix.get("sandbox"),
    }


def _figure(value):
    """A recorded figure as a reader reads it: 2,000,000 and 166.6667, not 50 digits.

    Only a number is touched; a declared word ("monthly", "SAR 1.2m") is returned
    exactly as it was recorded, because the explainer may not rewrite an input.
    """
    text = _text(value)
    try:
        number = Decimal(text)
    except (InvalidOperation, ValueError):
        return text
    if not number.is_finite():
        return text
    if number == number.to_integral_value():
        return format(number.to_integral_value(), ",f")
    return format(number.quantize(Decimal("0.0001")).normalize(), ",f")


def _input_rows(contract, inputs, provenance):
    rows = []
    schema = contract.get("inputs") or {}
    names = [name for name in schema if name in inputs]
    names += [name for name in sorted(inputs) if name not in names]
    for name in names:
        spec = schema.get(name) or {}
        source = provenance.get(name) or "declared by you"
        source = {"user": "declared by you", "owner": "declared by you",
                  "engine": "recorded by the engine", "default": "method default"}.get(source, source)
        rows.append([_humanise(name), spec.get("desc") or "declared input",
                     _figure(inputs.get(name)), source])
    return rows


def _output_rows(artifacts, outputs):
    rows = []
    if artifacts:
        for row in artifacts:
            rows.append([_humanise(row.get("metric") or row.get("id")),
                         _figure(row.get("value")), row.get("derivation") or ""])
        return rows
    for name in sorted(outputs or {}):
        rows.append([_humanise(name), _figure(outputs[name]), ""])
    return rows


def _join_sentences(items):
    """Join recorded sentences without leaving '.;' where one already ended."""
    cleaned = [str(item).strip().rstrip(".") for item in items if str(item or "").strip()]
    return "; ".join(cleaned) + ("." if cleaned else "")


_HEADLINE_KEYS = (
    "breakeven_units", "target_revenue", "npv", "irr", "net_income",
    "total_net_income", "profit", "base_profit", "total_depreciation",
    "total_assets", "equity_value", "mean", "statistic", "estimate", "value",
)


def _headline(outputs, artifacts):
    if artifacts:
        first = artifacts[0]
        return _humanise(first.get("metric") or first.get("id")) + ": " + _figure(first.get("value"))
    outputs = outputs or {}
    for name in _HEADLINE_KEYS:
        if name in outputs:
            return _humanise(name) + ": " + _figure(outputs[name])
    for name in outputs:
        return _humanise(name) + ": " + _figure(outputs[name])
    return ""


def _gaps_for(notes):
    gaps = []
    if not notes.get("formula"):
        gaps.append("The catalogue has no written formula for this method; the record shows the declared "
                    "figures and the recorded result, and the formula is not invented here.")
    if not notes.get("steps"):
        gaps.append("The catalogue has no written step list for this method; the record shows the declared "
                    "figures and the recorded result, and the steps are not invented here.")
    return gaps


def _checks_section(checks, records=False):
    if records:
        return _section("The checks", paragraphs=[
            "These are the checks the method declares. The pipeline only produces a delivery after its "
            "checks pass, so a recorded result is a checked result."],
            bullets=["%s: %s" % ("PASS" if ok else "FAIL", name) for name, ok in checks])
    return _section("How you know it is right", paragraphs=[
        "The method declares the checks below. A delivery is only produced after the checks pass, so their "
        "presence is the record that the method was checked; this document does not invent a per-check verdict."],
        bullets=list(checks))


