"""Teach-the-student explanation of a recorded computation (product layer).

The explainer is a **formatter of recorded data**, not a second engine and not a
model-written narrative.  It reads the case bundle or chat state, the committed
method-contract slice and the declared catalogue notes, and writes a document a
student can read, understand and defend:

    question -> why this method -> the method and its steps -> the declared
    figures -> the recorded result -> what it means -> checks -> common
    mistakes -> likely questions -> limits -> the record

Every figure in the document is copied from the bundle: an input value, an
output value, or a value the catalogue declares (a version, a section number).
If a method has no written formula/steps note, the document names that gap; it
never improvises a derivation.  No arithmetic is performed here.

The module imports no frozen core module.  It reads the committed
`data/explain_contracts_v0_1.json` (regenerated by
`scripts/generate_explain_contracts.py`) and the product catalogue.
"""

