class ExplainError(ValueError):
    """The recorded data cannot produce an explanation."""


def _load_contracts():
    try:
        with open(_DATA, encoding="utf-8") as stream:
            payload = json.load(stream)
    except (OSError, ValueError):
        return {}
    if payload.get("format") != "bp-explain-contracts/1":
        return {}
    return payload.get("methods") or {}


