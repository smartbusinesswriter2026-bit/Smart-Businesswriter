def has_computation(bundle):
    """Whether a stored case actually records a computation result."""
    if not isinstance(bundle, dict):
        return False
    appendix = ((bundle.get("delivery") or {}).get("appendix") or {})
    reperform = bundle.get("reperform") or {}
    if reperform.get("outputs"):
        return True
    if appendix.get("accounts") and appendix["accounts"].get("statements"):
        return True
    return False


def case_document(bundle):
    """A teachable explanation of one stored case bundle."""
    if not isinstance(bundle, dict):
        raise ExplainError("a case bundle object is required")
    delivery = bundle.get("delivery") or {}
    appendix = delivery.get("appendix") or {}
    reperform = bundle.get("reperform") or {}
    session = bundle.get("session") or {}
    work_plan = session.get("work_plan") or {}
    spec = session.get("spec") or {}
    method = ((reperform.get("method") or {}).get("id")
              or (appendix.get("method") or {}).get("id")
              or work_plan.get("method"))
    if not method:
        raise ExplainError("this case records no method to explain")
    contract = _contract(method)
    inputs = dict(reperform.get("inputs") or {})
    if not inputs:
        inputs = {name: (spec.get("inputs", {}).get(name) or {}).get("value")
                  for name in (spec.get("inputs") or {})}
        inputs = {name: value for name, value in inputs.items() if value is not None}
    if not inputs and not appendix.get("accounts"):
        raise ExplainError("this case records no computation result to explain")
    accounts = appendix.get("accounts") or {}
    if accounts:
        # The accounting engagement's `spec` is a large object; the explainer
        # summarises what was declared and then shows the stored journal and
        # statements, rather than printing the raw specification.
        spec_obj = inputs.get("spec") if isinstance(inputs.get("spec"), dict) else (spec.get("inputs") or {})
        period = spec_obj.get("period") if isinstance(spec_obj, dict) else {}
        inputs = {
            "period": (period.get("start", "") + " to " + period.get("end", "")) if isinstance(period, dict) else "",
            "currency": (spec_obj.get("currency") if isinstance(spec_obj, dict) else "") or "",
            "chart": "declared chart of accounts",
            "entries": "declared journal entries",
        }
        inputs = {name: value for name, value in inputs.items() if value}
        provenance = {name: "declared in the engagement" for name in inputs}
    else:
        provenance = {name: (spec.get("inputs", {}).get(name) or {}).get("provenance")
                      for name in inputs}
    outputs = reperform.get("outputs") or {}
    artifacts = case_export.artifact_rows(bundle)
    if not outputs and not artifacts and not appendix.get("accounts"):
        raise ExplainError("this case records no computation result to explain")
    key, info, notes = _notes(method, inputs)
    label = (info or {}).get("label") or _humanise(method)
    objective = (work_plan.get("objective") or bundle.get("title") or label)
    title = bundle.get("title") or objective or label
    figures = []

    sections = [
        _section("1. Problem", paragraphs=[_text(objective)]),
        _section("4. Solution Roadmap", paragraphs=[
            "Method: " + label + " (" + (contract.get("tier") or "recorded") + " method).",
            "The frozen method performed the arithmetic. These are the values it recorded; "
            "this document quotes them and does not recalculate them.",
        ]),
        _section("2. Given Data", paragraphs=[
            "These are the figures the run used. They are the values the bundle records; nothing was "
            "defaulted or rounded in this document."],
            table=_table(["Figure", "What it means", "Recorded value", "Where it came from"],
                         _input_rows(contract, inputs, provenance))),
        _section("3. Concepts, Formulas, and Assumptions", paragraphs=[
            contract.get("intended_use") or (info or {}).get("what")
            or "The method is the frozen method recorded for this run.",
            "It is a " + (contract.get("tier") or appendix.get("tier") or "recorded")
            + " method" + ((" (version " + contract["version"] + ")") if contract.get("version") else "") + ".",
        ]),
    ]
    formula = notes.get("formula")
    steps = notes.get("steps") or []
    mistakes = notes.get("common_mistakes") or []
    sections.append(_section(
        "3. Concepts, Formulas, and Assumptions",
        paragraphs=[("Declared formula: " + formula) if formula else None,
                    (info or {}).get("what") or None],
        bullets=([("Step %d. %s" % (index + 1, step)) for index, step in enumerate(steps)]
                 if steps else None),
    ))
    if mistakes:
        sections.append(_section("3. Concepts, Formulas, and Assumptions", bullets=mistakes))

    output_rows = _output_rows(artifacts, outputs)
    sections.append(_section(
        "5. Explanation",
        paragraphs=[
            "The frozen method performed the arithmetic. These are the values it recorded; this document "
            "quotes them and does not recalculate them.",
        ],
        table=_table(["Result", "Recorded value", "Recorded derivation"], output_rows) if output_rows else None,
    ))
    report = delivery.get("report")
    if isinstance(report, str) and report.strip():
        sections.append(_section("5. Explanation", paragraphs=report.splitlines()))

    accounts = appendix.get("accounts") or {}
    if accounts:
        sections.extend(_accounting_sections(accounts, contract, notes))

    checks = appendix.get("tests") or contract.get("planned_checks") or []
    if accounts and isinstance(accounts.get("checks"), list):
        sections.append(_checks_section([(str(item[0]), bool(item[1]) if len(item) > 1 else False)
                                         for item in accounts["checks"]], records=True))
    elif checks:
        sections.append(_checks_section(checks))

    assumptions = list(appendix.get("assumptions") or []) or list(contract.get("assumptions") or [])
    limitations = list(appendix.get("limitations") or []) or list(contract.get("limitations") or [])
    defaults = list(contract.get("defaults") or [])
    if assumptions:
        sections.append(_section("3. Concepts, Formulas, and Assumptions", bullets=assumptions))
    if defaults:
        sections.append(_section(
            "3. Concepts, Formulas, and Assumptions",
            bullets=["%s: %s Impact: %s" % (item.get("question"), item.get("default_chosen"),
                                            item.get("impact"))
                     for item in defaults if isinstance(item, dict)]))
    if limitations:
        sections.append(_section("6. Interpretation", bullets=limitations))
    unsupported = contract.get("unsupported_use")
    if unsupported:
        sections.append(_section("6. Interpretation", paragraphs=[unsupported]))

    headline = _headline(outputs, artifacts)
    sections.append(_section(
        "6. Interpretation",
        bullets=[
            "What was the question? " + _text(objective),
            "Why this method? " + (contract.get("intended_use") or "It is the method recorded for this run."),
            "What did you declare? " + _sentence_list(
                ["%s (%s)" % (_humanise(name), _text(inputs[name])) for name in inputs]) + ".",
            "What did the engine return? " + (headline or "The recorded values are listed above."),
            "What did you assume? " + (_join_sentences(assumptions) if assumptions else
                                      "The method's declared defaults, listed above."),
            "What would change the answer? " + (unsupported or "The recorded assumptions and limits name the "
                                                               "conditions under which the result would not hold."),
            "How do you know it is right? The method declares the checks above, and the delivery records the "
            "hashes below.",
            "What does it not prove? " + (_join_sentences(limitations) if limitations else
                                         "It proves only what the method contract supports."),
        ],
    ))
    record = _record(bundle)
    sections.append(_section("2. Given Data", table=_table(
        ["Field", "Recorded value"],
        [[_humanise(name), _text(value)] for name, value in record.items() if value not in (None, "", {})])))

    for row in _input_rows(contract, inputs, provenance):
        figures.append({"label": row[0], "value": row[2], "source": "input"})
    for row in output_rows:
        figures.append({"label": row[0], "value": row[1], "source": "output"})

    return {
        "format": FORMAT,
        "kind": "computation",
        "title": "How this was solved: " + title,
        "subtitle": label + " (case " + _text(bundle.get("id") or "not recorded") + ")",
        "label": label,
        "sections": [section for section in sections if section.get("paragraphs")
                     or section.get("bullets") or section.get("table")],
        "figures": figures,
        "gaps": _gaps_for(notes) + ([] if checks else [
            "The bundle records no check names for this method."]),
        "record": record,
        "_tool": key,
        "_method": method,
    }


def _accounting_sections(accounts, contract, notes):
    """The teachable accounting cycle, built from the stored strings."""
    out = []
    statements = accounts.get("statements_export")
    journal = accounts.get("journal_export")
    t_accounts = accounts.get("t_accounts_export") or {}
    if notes.get("steps"):
        out.append(_section("The accounting cycle", paragraphs=[
            "The engagement is solved in the order below. Each line is the catalogue's declared procedure; "
            "the journal, T-accounts and statements that follow are the stored records of this run."],
            bullets=["Step %d. %s" % (index + 1, step) for index, step in enumerate(notes["steps"])]))
    if isinstance(journal, str) and journal.strip():
        out.append(_section("The journal, as recorded", paragraphs=journal.splitlines()))
    if isinstance(t_accounts, dict) and t_accounts:
        for code in sorted(t_accounts):
            out.append(_section("T-account " + _text(code), paragraphs=_lines(t_accounts[code]), level=2))
    if isinstance(statements, dict) and statements:
        for name in ("trial_balance", "income_statement", "balance_sheet", "cash_flow",
                     "reconciliation", "notes"):
            part = statements.get(name)
            if isinstance(part, str) and part.strip():
                out.append(_section(_humanise(name) + ", as recorded", paragraphs=part.splitlines(), level=2))
    elif isinstance(statements, str) and statements.strip():
        out.append(_section("The statements, as recorded", paragraphs=statements.splitlines()))
    return out


# --- chat paper ------------------------------------------------------------

def has_chat_computation(state):
    """Whether a paper records at least one delivered computation."""
    if not isinstance(state, dict):
        return False
    for entry in (state.get("computations") or {}).values():
        if isinstance(entry, dict) and entry.get("ok") and entry.get("result"):
            return True
    return False


def _draft_outline(draft):
    outline = draft.get("outline")
    if isinstance(outline, list) and outline:
        return [item for item in outline if isinstance(item, dict)]
    out = []
    for item in draft.get("sections") or []:
        if isinstance(item, dict):
            out.append(item)
        elif isinstance(item, (list, tuple)) and len(item) == 2:
            out.append({"heading": item[0], "level": 1, "lines": item[1]})
    return out


def _draft_lines(draft, headings):
    outline = _draft_outline(draft)
    wanted = {str(heading).strip().lower() for heading in headings if heading}
    for item in outline:
        if str(item.get("heading") or "").strip().lower() in wanted:
            return _lines(item.get("lines"))
    return []


def _plan_meta(state, key):
    plan = state.get("plan") or {}
    for block in plan.get("blocks") or []:
        if block.get("key") == key:
            return block
    for row in ((state.get("selection") or {}).get("selected") or []):
        if row.get("key") == key:
            return row
    for capability in plan.get("capabilities") or []:
        if capability.get("key") == key:
            return capability
    return {}


def paper_document(state):
    """A teachable explanation of a paper that carries computations."""
    if not isinstance(state, dict):
        raise ExplainError("a chat state object is required")
    draft = state.get("draft") or {}
    computations = {key: value for key, value in (state.get("computations") or {}).items()
                    if isinstance(value, dict) and value.get("ok") and value.get("result")}
    if not computations:
        raise ExplainError("this paper records no computation to explain")
    title = draft.get("title") or state.get("brief") or "Paper"
    plan = state.get("plan") or {}
    framework = str(state.get("framework") or plan.get("framework") or "").lower()
    profile = state.get("profile") or plan.get("profile") or "paper"
    profile_label = plan.get("label") or ""
    if not profile_label:
        profile_label = (_FRAMEWORK_LABELS.get(framework, _humanise(framework)) + " paper"
                         if framework else _humanise(profile))
    level = state.get("level") or plan.get("level")
    level_label = state.get("level_label") or plan.get("level_label") or _humanise(level)
    mode_label = state.get("mode_label") or plan.get("mode_label") or _humanise(state.get("mode") or plan.get("mode"))
    # A chat paper records its sections on the draft; a business plan records them
    # on the plan.  Read whichever exists, and omit the sentence when neither does.
    headings = [item.get("heading") for item in (draft.get("outline") or []) if item.get("heading")]
    if not headings:
        headings = [item.get("heading") for item in (plan.get("sections") or []) if item.get("heading")]
    built = ["Profile: " + _text(profile_label)
             + (" (" + ", ".join(_text(part) for part in (level_label, mode_label) if part) + ")"
                if any((level_label, mode_label)) else "") + "."]
    if headings:
        built.append("Sections: " + _sentence_list(headings) + ".")
    count = len(computations)
    count_label = str(count) + " computation" + ("" if count == 1 else "s")
    sections = [
        _section("The question and the thesis", paragraphs=[
            _text(state.get("brief") or (state.get("answers") or {}).get("decision") or "The paper's brief."),
            "The paper records the decision, the framework and every figure below; this companion explains "
            "how those parts were solved.",
        ]),
        _section("How the paper is built", paragraphs=built),
    ]
    gaps = [str(gap) for gap in (state.get("gaps") or []) if str(gap or "").strip()]
    sections.append(_section(
        "Evidence and named gaps",
        paragraphs=[
            "The paper's retrieved sources are recorded in its reference list. A dimension without evidence is "
            "named as a gap; it is not filled with an invented finding.",
        ],
        bullets=(gaps or ["No gap was recorded for this paper."]),
    ))

    computation_sections = []
    summary_rows = []
    figures = []
    all_limitations = []
    all_unsupported = []
    for index, (key, entry) in enumerate(computations.items(), start=1):
        meta = _plan_meta(state, key)
        method = entry.get("method") or meta.get("method") or key
        contract = _contract(method)
        tool_key, info, notes = _notes(method, entry.get("inputs"))
        label = meta.get("label") or (info or {}).get("label") or _humanise(key)
        heading = "%d. %s" % (index, label)
        inputs = entry.get("inputs") or {}
        outputs = entry.get("result") or {}
        input_rows = _input_rows(contract, inputs, {})
        output_rows = _output_rows([], outputs)
        summary_rows.append([label, method, _headline(outputs, []) or "recorded"])
        slot = meta.get("slot")
        slot_label = slot[-1] if isinstance(slot, list) and slot else None
        citation = _draft_lines(draft, [meta.get("label"), label, slot_label])
        body = [
            "Why this method: " + (contract.get("intended_use") or (info or {}).get("what")
                                   or "It is the method the paper selected."),
        ]
        if notes.get("formula"):
            body.append("Declared formula: " + notes["formula"])
        body.append("The paper reports this computation under " +
                    _text(slot_label or label) + ".")
        section = _section(heading, paragraphs=body,
                           table=_table(["Figure", "What it means", "Recorded value", "Where it came from"],
                                        input_rows) if input_rows else None)
        computation_sections.append(section)
        if notes.get("steps"):
            computation_sections.append(_section(
                heading + " - the steps",
                bullets=["Step %d. %s" % (step_index + 1, step)
                         for step_index, step in enumerate(notes["steps"])]))
        if output_rows:
            computation_sections.append(_section(
                heading + " - what the engine returned",
                paragraphs=["The frozen method performed the arithmetic; these are the values it recorded."],
                table=_table(["Result", "Recorded value", "Recorded derivation"], output_rows)))
        if citation:
            computation_sections.append(_section(
                heading + " - how the paper reports it",
                paragraphs=citation))
        if notes.get("common_mistakes"):
            computation_sections.append(_section(
                heading + " - common mistakes", bullets=notes["common_mistakes"]))
        limitations = list(contract.get("limitations") or [])
        if limitations:
            all_limitations.extend(limitations)
            computation_sections.append(_section(heading + " - limits", bullets=limitations))
        if contract.get("unsupported_use"):
            all_unsupported.append(contract["unsupported_use"])
        for row in input_rows:
            figures.append({"label": row[0], "value": row[2], "source": "input:" + key})
        for row in output_rows:
            figures.append({"label": row[0], "value": row[1], "source": "output:" + key})
        gaps.extend(_gaps_for(notes))

    sections.append(_section("The computations at a glance", table=_table(
        ["Computation", "Method", "Headline recorded value"], summary_rows)))
    sections.extend(computation_sections)
    sections.append(_section(
        "How the computations support the argument",
        paragraphs=[
            "The computations are inputs to the paper's argument, not forecasts or recommendations. The paper "
            "reports each recorded value under its own section; the Discussion integrates them with the "
            "evidence rather than repeating the arithmetic.",
        ]))
    sections.append(_section(
        "If your professor asks",
        bullets=[
            "What was the paper asked to do? " + _text(state.get("brief") or "The paper's brief."),
            "Why these computations? " + _sentence_list([row[0] for row in summary_rows]) + ".",
            "What did you declare? The figures in the tables above; each is the value the paper recorded.",
            "What did the engine return? " + _sentence_list([row[2] for row in summary_rows]) + ".",
            "What did you assume? The method contracts' assumptions and defaults, listed with each computation.",
            "What would change the answer? " + (_join_sentences(all_unsupported) if all_unsupported else
                                                "The limits recorded with each computation."),
            "What does the paper not prove? " + (_join_sentences(sorted(set(all_limitations)))
                                                 if all_limitations else
                                                 "It proves only what each method contract supports."),
        ]))
    if gaps:
        sections.append(_section("Named gaps", bullets=sorted(set(gaps))))
    sections.append(_section("For the record", table=_table(
        ["Field", "Recorded value"],
        [["Paper", title], ["Profile", profile_label], ["Level", level_label],
         ["Style", (state.get("answers") or {}).get("style") or plan.get("style")],
         ["Computations", str(len(computations))],
         ["Paper record", "This companion explains the paper; the paper itself is the submitted record."]])))

    return {
        "format": FORMAT,
        "kind": "paper",
        "title": "How this paper was solved: " + title,
        "subtitle": profile_label + " - " + count_label,
        "label": profile_label,
        "sections": [section for section in sections if section.get("paragraphs")
                     or section.get("bullets") or section.get("table")],
        "figures": figures,
        "gaps": gaps,
        "record": {"paper": title, "profile": profile_label,
                   "level": level_label,
                   "style": (state.get("answers") or {}).get("style") or plan.get("style")},
    }


# --- rendering and packaging ------------------------------------------------

def docx_bytes(document):
    return docx.render_note(document["title"], document.get("subtitle", ""), document["sections"])


def html_bytes(document):
    from . import explain_html
    return explain_html.render(document).encode("utf-8")


def document_bytes(document, fmt="docx"):
    if fmt == "docx":
        return docx_bytes(document), DOCX_MIME, "docx"
    if fmt == "html":
        return html_bytes(document), HTML_MIME, "html"
    raise ExplainError("the explanation can be produced as docx or html, not %r" % fmt)


def filename(title, fmt="docx"):
    return slug(title) + "-explainer." + ("docx" if fmt == "docx" else "html")


def zip_pair(title, paper_bytes, paper_ext, explainer_bytes, explainer_ext):
    """One ZIP with the paper and the explainer as separate files."""
    stem = slug(title)
    paper_name = stem + "." + paper_ext.lstrip(".")
    explainer_name = stem + "-explainer." + explainer_ext.lstrip(".")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in ((paper_name, paper_bytes), (explainer_name, explainer_bytes)):
            archive.writestr(zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0)), data)
    payload = buf.getvalue()
    contents = [{"filename": name, "bytes": len(data), "sha256": sha256(data).hexdigest()}
                for name, data in ((paper_name, paper_bytes), (explainer_name, explainer_bytes))]
    return payload, contents, stem + "-submission.zip"
