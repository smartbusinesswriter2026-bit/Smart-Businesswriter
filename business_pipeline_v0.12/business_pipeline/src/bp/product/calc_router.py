#: The five answers the chat may give.  Two refusals mean different things:
#: `unsupported` is a roadmap statement, `out_of_scope` is a boundary.
OUTCOMES = ("run", "need_inputs", "choose", "unsupported", "out_of_scope")

MAX_TEXT = 600


class PlanError(ValueError):
    """The message cannot be planned at all (empty, wrong type, too long)."""


def _load_inputs():
    with open(_DATA, encoding="utf-8") as stream:
        payload = json.load(stream)
    if payload.get("format") != INPUTS_FORMAT:
        raise RuntimeError("calculator input slice has an unexpected format")
    return payload["methods"]


