# --- helpers ----------------------------------------------------------------

def _norm(text):
    """Lower-cased, single-spaced text with control characters removed."""
    text = re.sub(r"[\x00-\x1f\x7f\x85\u2028\u2029]", " ", text)
    return re.sub(r"\s+", " ", text).strip().lower()


def _tokens(text):
    return [word for word in _WORD.findall(text) if len(word) > 2 and word not in STOP]


def _has(text, phrase):
    """Whole-word/phrase containment, so 'mean' does not fire inside 'meaning'."""
    return re.search(r"(?<![a-z0-9])" + re.escape(phrase) + r"(?![a-z0-9])", text) is not None


def _numbers(text):
    return [match.group(0) for match in _NUM.finditer(text)]


def _first_number_between(text, start, end):
    """The first number in text[start:end], or None."""
    for match in _NUM.finditer(text, max(0, start), max(0, end)):
        return match.group(0)
    return None


def _percent_follows(text, number):
    """True when the matched number is written as a percentage ('10%')."""
    pattern = re.escape(number) + r"\s*%"
    return re.search(pattern, text) is not None


def _comma_run(text):
    """The longest comma-separated run of numbers ('-1000, 400, 400, 400')."""
    pattern = re.compile(r"-?\d+(?:\.\d+)?(?:\s*,\s*-?\d+(?:\.\d+)?)+")
    best = None
    for match in pattern.finditer(text):
        numbers = _NUM.findall(match.group(0))
        if best is None or len(numbers) > len(best):
            best = numbers
    return best


def _is_bare_arithmetic(text):
    """True for '2 + 2', '15% of 84,000', '1200/8' - filler words allowed."""
    if not _NUM.search(text):
        return False
    words = [word for word in _WORD.findall(text) if word not in _ARITH_WORDS]
    if words:
        return False
    return any(sign in text for sign in ("-", "+", "*", "/", "\u00d7", "\u00f7", "%", "^"))


def _segments(text):
    """The sentence split into figure-sized pieces, so names bind to their own number."""
    return [part for part in re.split(r"[,;]|\band\b", text) if part.strip()]


def _scalar_inputs(schema, text):
    """Bind each scalar input to the number that sits nearest its own name.

    Only the name that appears in the sentence binds, and only within its own
    segment (comma / 'and' piece), so '1200 fixed cost, price 20' cannot give
    the price the fixed cost's number.
    """
    segments = _segments(text)
    found = {}
    for name in sorted(schema):
        spec = schema[name] or {}
        if spec.get("type") in LIST_TYPES:
            continue
        aliases = sorted(INPUT_WORDS.get(name, [name.replace("_", " ")]), key=len, reverse=True)
        best = None
        for alias in aliases:                      # longest alias that occurs anywhere wins
            for index, segment in enumerate(segments):
                match = re.search(r"(?<![a-z0-9])" + re.escape(alias) + r"(?![a-z0-9])", segment)
                if not match:
                    continue
                numbers = list(_NUM.finditer(segment))
                if not numbers:
                    continue
                distance, number = min((abs(item.start() - match.start()), item.group(0))
                                       for item in numbers)
                if best is None or distance < best[0] or (distance == best[0] and index < best[1]):
                    best = (distance, index, number)
                break
            if best is not None:
                break
        if best is not None:
            found[name] = best[2]
    return found


def _number_for(text, names):
    """The number stated next to the first name that appears in the sentence.

    Looks after the name first, then before it, so both "fixed cost 1200" and
    "1200 of fixed cost" are read - but only the text between the name and the
    next name/number boundary, never a number from a different field.
    """
    best = None
    for name in names:
        for match in re.finditer(r"(?<![a-z0-9])" + re.escape(name) + r"(?![a-z0-9])", text):
            after = _first_number_between(text, match.end(), match.end() + 24)
            before = _first_number_between(text, match.start() - 20, match.start())
            candidate = after if after is not None else before
            if candidate is not None:
                # prefer the longest name (most specific phrase), then earliest position
                key = (len(name), -match.start())
                if best is None or key > best[0]:
                    best = (key, candidate)
                break
    return None if best is None else best[1]


def _tools():
    """The closed tool catalogue (imported lazily; the product layer owns it)."""
    from . import subjects

    return subjects.TOOL_INFO


def _score(text, tokens):
    """A deterministic score per tool: phrase hits weigh more than word overlap."""
    token_set = set(tokens)
    scores = {}
    for key, info in _tools().items():
        if info["method"] not in INPUTS:
            continue        # a tool without a declared schema cannot be planned here
        score = 0
        for phrase in [info["label"].lower()] + SYNONYMS.get(key, []):
            if _has(text, phrase):
                score += 2 + len(phrase.split())
        overlap = token_set & set(_tokens(info["label"] + " " + info["what"]))
        score += len(overlap)
        if score:
            scores[key] = score
    return scores


def _alt(key):
    info = _tools()[key]
    method = info["method"]
    return {"tool": key, "label": info["label"], "method": method,
            "tier": (INPUTS.get(method) or {}).get("tier")}


def _payload(outcome, text, reason="", tool=None, inputs=None, missing=None,
             alternatives=None, notes=None):
    info = _tools().get(tool) if tool else None
    method = info["method"] if info else None
    meta = INPUTS.get(method) or {}
    return {
        "format": FORMAT,
        "outcome": outcome,
        "reason": reason,
        "tool": tool,
        "method": method,
        "label": info["label"] if info else None,
        "tier": meta.get("tier"),
        "version": meta.get("version"),
        "inputs": inputs or {},
        "missing": missing or [],
        "alternatives": alternatives or [],
        "notes": notes or [],
        "text_length": len(text),
    }


def _unsupported_topics(text):
    return [topic for topic, phrases in sorted(UNSUPPORTED.items())
            if any(_has(text, phrase) for phrase in phrases)]


def _extract(text, tool):
    """Read only the figures the sentence actually names.  Nothing is defaulted."""
    schema = (INPUTS.get(_tools()[tool]["method"]) or {}).get("inputs") or {}
    notes, missing = [], []
    inputs = dict(_scalar_inputs(schema, text))
    for name in sorted(inputs):
        number = inputs[name]
        if _percent_follows(text, number):
            del inputs[name]
            if name not in OPTIONAL_INPUTS:
                missing.append(name)
            notes.append("'" + number + "%' is written as a percentage: enter " + name +
                         " as a decimal (for example 0.10). The calculator does not convert it.")
    run = _comma_run(text)
    primary = [name for name in schema
               if (schema[name] or {}).get("type") in LIST_TYPES and name in PRIMARY_LISTS]
    for name in sorted(schema):
        spec = schema[name] or {}
        if spec.get("type") not in LIST_TYPES:
            if name not in inputs and name not in missing and name not in OPTIONAL_INPUTS:
                missing.append(name)
            continue
        if name in inputs:
            continue
        numbers = [n for n in _numbers(text) if not _percent_follows(text, n)]
        aliases = INPUT_WORDS.get(name, [name.replace("_", " ")])
        phrase_hit = any(_has(text, word) for word in aliases)
        if phrase_hit and numbers:
            inputs[name] = run if run else numbers
        elif run and primary == [name]:
            inputs[name] = run
        elif name in OPTIONAL_INPUTS:
            continue
        else:
            missing.append(name)
    return inputs, sorted(missing), notes


def plan(text):
    """Plan one message.  Returns a payload; raises PlanError only for non-text."""
    if not isinstance(text, str):
        raise PlanError("the message must be text")
    if not text.strip():
        raise PlanError("the message is empty")
    if len(text) > MAX_TEXT:
        raise PlanError("the message is longer than %d characters" % MAX_TEXT)
    norm = _norm(text)

    # 1. the message is data, never an instruction
    for phrase in INSTRUCTION:
        if _has(norm, phrase):
            return _payload("out_of_scope", text,
                            "instruction: the message reads as an instruction, and a message can "
                            "never change what this calculator does")
    # 2. bare arithmetic is the parked decision, not a feature
    if _is_bare_arithmetic(norm):
        return _payload("out_of_scope", text,
                        "bare_arithmetic: the calculator runs recorded business methods and does "
                        "not evaluate expressions")
    # 3. algebra homework is not a business computation
    if re.search(r"\b(solve|equation|algebra)\b", norm) and "=" in norm:
        return _payload("out_of_scope", text,
                        "not_business: this calculator runs recorded business methods (finance, "
                        "accounting, economics, operations, marketing, people, statistics); an "
                        "algebra problem is not one of them")
    # 4. other subjects and personal advice are outside what this engine is
    for phrase in NON_BUSINESS:
        if _has(norm, phrase):
            return _payload("out_of_scope", text,
                            "not_business: this calculator runs recorded business methods (finance, "
                            "accounting, economics, operations, marketing, people, statistics); '" +
                            phrase + "' is not one of them")
    # 4. business, but nothing frozen computes it
    topics = _unsupported_topics(norm)
    if topics:
        return _payload("unsupported", text,
                        "not_built: " + ", ".join(topics) + " - no frozen method computes this, and "
                        "the calculator will not estimate it",
                        alternatives=[_alt(k) for k in ("npv", "ratios", "forecast")])

    # 5. route against the closed catalogue
    tokens = _tokens(norm)
    scores = _score(norm, tokens)
    ranked = sorted(scores.items(), key=lambda item: (-item[1], item[0]))
    clues = [key for word, keys in CLUES.items() if _has(norm, word) for key in keys]
    if len(ranked) >= 2 and ranked[1][1] >= 4 and ranked[0][1] - ranked[1][1] <= 1:
        alternatives = [key for key, value in ranked[:3] if value >= 4]
        return _payload("choose", text,
                        "ambiguous: more than one frozen method fits, and the calculator does not guess",
                        alternatives=[_alt(k) for k in alternatives])
    if ranked and ranked[0][1] >= 4:
        tool = ranked[0][0]
        inputs, missing, notes = _extract(norm, tool)
        if missing:
            return _payload("need_inputs", text, "missing: " + ", ".join(missing), tool=tool,
                            inputs=inputs, missing=missing, notes=notes)
        return _payload("run", text, "ready: confirm and the method runs", tool=tool,
                        inputs=inputs, notes=notes)
    if clues:
        return _payload("choose", text, "ambiguous: the sentence names a family, not a method",
                        alternatives=[_alt(k) for k in list(dict.fromkeys(clues))[:3]])
    nearest = [key for key, value in ranked[:3]]
    return _payload("unsupported", text, "no_method: no frozen method matches this sentence",
                    alternatives=[_alt(k) for k in nearest])


