def _fill_catalogue_ids():
    """Resolve the subject definitions that delegate their catalogue to tags.

    The result is deterministic because CATALOGUE is sorted by id and the
    registry's discipline tags are exact strings.
    """
    for definition in SUBJECT_DEFS:
        if definition["catalogue_ids"] is not None:
            continue
        definition["catalogue_ids"] = sorted(
            record["id"] for record in CATALOGUE.values()
            if any(tag in definition["disciplines"] for tag in record["disciplines"]))


_fill_catalogue_ids()

