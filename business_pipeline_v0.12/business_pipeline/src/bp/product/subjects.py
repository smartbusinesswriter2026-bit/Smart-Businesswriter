def _tool(key):
    """A fresh launcher descriptor for one TOOL_INFO entry."""
    info = TOOL_INFO[key]
    return {"kind": "compute", "key": key, "preset": info["preset"],
            "method": info["method"], "label": info["label"], "what": info["what"]}


def _worksheet(catalogue_id):
    """A fresh launcher descriptor for one T4 worksheet."""
    info = WORKSHEETS[catalogue_id]
    return {"kind": "worksheet", "key": catalogue_id, "catalogue_id": info["catalogue_id"],
            "template": info["template"], "label": info["label"], "what": info["what"]}


def _subject_definition(subject_id):
    for definition in SUBJECT_DEFS:
        if definition["id"] == subject_id:
            return definition
    raise SubjectNotFound("no subject is declared with id %r" % subject_id)


def exists(subject_id):
    """Whether a subject id is declared."""
    return any(definition["id"] == subject_id for definition in SUBJECT_DEFS)


def catalogue():
    """Summary rows for the subject gallery, in the declared order."""
    rows = []
    for definition in SUBJECT_DEFS:
        rows.append({
            "id": definition["id"],
            "label": definition["label"],
            "icon": definition["icon"],
            "summary": definition["summary"],
            "disciplines": list(definition["disciplines"]),
            "cross_cutting": bool(definition["cross_cutting"]),
            "tool_count": len(definition["tools"]),
            "worksheet_count": len(definition["worksheets"]),
            "catalogue_count": len(definition["catalogue_ids"]),
        })
    return {"format": FORMAT, "subjects": rows}


def detail(subject_id):
    """The full subject page: launchable tools, worksheets and catalogue rows."""
    definition = _subject_definition(subject_id)
    catalogue_rows = []
    for catalogue_id in definition["catalogue_ids"]:
        record = CATALOGUE.get(catalogue_id)
        if record is None:
            # The guard test makes this impossible for shipped data; a visible
            # refusal is still better than silently dropping a subject's item.
            catalogue_rows.append({"id": catalogue_id, "name": "not recorded",
                                   "implementation_status": "not recorded", "template": None,
                                   "linked_methods": [], "disciplines": []})
            continue
        catalogue_rows.append({
            "id": record["id"],
            "name": record["name"],
            "implementation_status": record["implementation_status"],
            "template": record["template"],
            "linked_methods": [item["method_id"] for item in record["linked_methods"]],
            "disciplines": list(record["disciplines"]),
        })
    return {
        "format": FORMAT,
        "id": definition["id"],
        "label": definition["label"],
        "icon": definition["icon"],
        "summary": definition["summary"],
        "disciplines": list(definition["disciplines"]),
        "cross_cutting": bool(definition["cross_cutting"]),
        "tools": [_tool(key) for key in definition["tools"]],
        "worksheets": [_worksheet(cid) for cid in definition["worksheets"]],
        "catalogue": catalogue_rows,
    }


def methods_for(subject_id):
    """Every frozen method id a subject page can launch (tools + worksheets)."""
    definition = _subject_definition(subject_id)
    methods = [TOOL_INFO[key]["method"] for key in definition["tools"]]
    methods.extend(WORKSHEETS[cid]["template"] for cid in definition["worksheets"])
    return methods


def filter_cases(summaries, subject_id):
    """Stored case summaries whose recorded method belongs to the subject.

    A corrupt summary has no method and is therefore not claimed by any
    subject; it stays visible on the case shelf instead.
    """
    methods = set(methods_for(subject_id))
    return [summary for summary in summaries
            if not summary.get("corrupt") and summary.get("method") in methods]


def compute_tools():
    """The deduplicated union of compute tools across the subjects.

    The Calculator's guard consumes this: one source of truth for the subject
    pages and the rail Calculator.
    """
    seen = set()
    tools = []
    for definition in SUBJECT_DEFS:
        for key in definition["tools"]:
            if key in seen:
                continue
            seen.add(key)
            tools.append(_tool(key))
    return tools


def calculator_groups():
    """The Calculator's tool groups, in business-function order."""
    groups = []
    for group in CALCULATOR_GROUPS:
        groups.append({
            "id": group["id"],
            "label": group["label"],
            "tools": [_tool(key) for key in group["tools"]],
        })
    return {"format": CALCULATOR_FORMAT, "groups": groups,
            "note": ("Every calculation is a frozen method run through the normal pipeline. "
                     "The Calculator arranges inputs and launches the method; it computes nothing. "
                     "Typed free-form arithmetic is not supported: it would be a second arithmetic path.")}


