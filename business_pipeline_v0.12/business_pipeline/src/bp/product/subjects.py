def _tool(key, subject_id=None):
    """A fresh launcher descriptor for one TOOL_INFO entry, with student notes."""
    info = TOOL_INFO[key]
    note = STUDENT_NOTES.get(key, {})
    groups = SUBJECT_GROUPS.get(subject_id, {})
    periods = SUBJECT_PERIODS.get(subject_id, {})
    return {"kind": "compute", "key": key, "preset": info["preset"],
            "method": info["method"], "label": info["label"], "what": info["what"],
            "level": note.get("level"),
            "formula": note.get("formula"),
            "steps": list(note.get("steps", [])),
            "common_mistakes": list(note.get("common_mistakes", [])),
            "diagram": note.get("diagram"),
            "related": list(note.get("related", [])),
            "group": groups.get(key),
            "period": periods.get(key)}


def _worksheet(catalogue_id):
    """A fresh launcher descriptor for one T4 worksheet."""
    info = WORKSHEETS[catalogue_id]
    return {"kind": "worksheet", "key": catalogue_id, "catalogue_id": info["catalogue_id"],
            "template": info["template"], "label": info["label"], "what": info["what"]}


def _subject_definition(subject_id):
    for definition in SUBJECT_DEFS:
        if definition["id"] == subject_id:
            return definition
    raise SubjectNotFound("no subject is declared with id %r" % subject_id)


def exists(subject_id):
    """Whether a subject id is declared."""
    return any(definition["id"] == subject_id for definition in SUBJECT_DEFS)


#: Short, student-facing names for the four delivery forms.  The long status
#: sentence stays in `implementation_status` so nothing is lost.
FORM_SHORT = {"computed": "Computed", "worksheet": "Worksheet",
              "read_only": "No worksheet yet", "theory": "Reading lens"}


def _record_form(record):
    """The delivery form, tolerant of a CATALOGUE slice written before the form field."""
    return record.get("form") or (
        "theory" if record.get("type") == "T"
        else "worksheet" if record.get("template")
        else "computed" if record.get("linked_methods")
        else "read_only")


def _catalogue_row(record):
    form = _record_form(record)
    disciplines = list(record["disciplines"])
    return {
        "id": record["id"],
        "name": record["name"],
        "type": record.get("type"),
        "form": form,
        "status_short": record.get("status_short") or (
            "Method not built" if form == "read_only" and record.get("type") == "Q" else FORM_SHORT[form]),
        "status_note": record.get("status_note") or record["implementation_status"],
        "implementation_status": record["implementation_status"],
        "structures": record.get("summary", ""),
        "evidence_needs": record.get("evidence_needs", ""),
        "template": record["template"],
        "linked_methods": [item["method_id"] for item in record["linked_methods"]],
        "disciplines": disciplines,
        "discipline_label": DISCIPLINE_LABELS.get(disciplines[0], disciplines[0]) if disciplines else "other",
    }


def catalogue():
    """Summary rows for the subject gallery, in the declared order."""
    rows = []
    for definition in SUBJECT_DEFS:
        worksheet_ids = set(definition["worksheets"])
        records = [CATALOGUE[cid] for cid in definition["catalogue_ids"]
                   if cid not in worksheet_ids and cid in CATALOGUE]
        rows.append({
            "id": definition["id"],
            "label": definition["label"],
            "icon": definition["icon"],
            "summary": definition["summary"],
            "disciplines": list(definition["disciplines"]),
            "discipline_labels": [DISCIPLINE_LABELS.get(tag, tag) for tag in definition["disciplines"]],
            "cross_cutting": bool(definition["cross_cutting"]),
            "tool_count": len(definition["tools"]),
            "worksheet_count": len(definition["worksheets"]),
            "record_count": sum(1 for record in records if _record_form(record) != "theory"),
            "theory_count": sum(1 for record in records if _record_form(record) == "theory"),
            "catalogue_count": len(definition["catalogue_ids"]),
        })
    return {"format": FORMAT, "subjects": rows}


def detail(subject_id):
    """The full subject page: launchable tools, worksheets and catalogue rows.

    `catalogue` keeps every assigned record (the API/guard view).  `records`
    and `theories` are the display view: a capability that already has a
    worksheet is not repeated as a catalogue row, and theories are separated
    from the buildable records because they are reading lenses by design.
    """
    definition = _subject_definition(subject_id)
    catalogue_rows = []
    for catalogue_id in definition["catalogue_ids"]:
        record = CATALOGUE.get(catalogue_id)
        if record is None:
            # The guard test makes this impossible for shipped data; a visible
            # refusal is still better than silently dropping a subject's item.
            catalogue_rows.append({"id": catalogue_id, "name": "not recorded", "type": None,
                                   "form": "read_only", "status_short": "Not recorded",
                                   "status_note": "not recorded", "implementation_status": "not recorded",
                                   "template": None, "linked_methods": [], "disciplines": []})
            continue
        catalogue_rows.append(_catalogue_row(record))
    worksheet_ids = set(definition["worksheets"])
    records = [row for row in catalogue_rows
               if row["id"] not in worksheet_ids and row["form"] != "theory"]
    theories = [row for row in catalogue_rows
                if row["id"] not in worksheet_ids and row["form"] == "theory"]
    return {
        "format": FORMAT,
        "id": definition["id"],
        "label": definition["label"],
        "icon": definition["icon"],
        "summary": definition["summary"],
        "disciplines": list(definition["disciplines"]),
        "discipline_labels": [DISCIPLINE_LABELS.get(tag, tag) for tag in definition["disciplines"]],
        "cross_cutting": bool(definition["cross_cutting"]),
        "guidance": definition.get("guidance"),
        "tools": [_tool(key, definition["id"]) for key in definition["tools"]],
        "worksheets": [_worksheet(cid) for cid in definition["worksheets"]],
        "catalogue": catalogue_rows,
        "records": records,
        "theories": theories,
        "glossary": list(GLOSSARIES.get(subject_id, [])),
    }


def _match_words(text):
    return [word for word in re.findall(r"[a-z][a-z0-9'-]+", (text or "").lower())
            if len(word) >= 3 and word not in _MATCH_STOP]


def match_frameworks(text, limit=5):
    """Suggest worksheets for a plain-language case description.

    A deterministic reading aid in the product layer: it scores the words in the
    description against the worksheet label and the catalogue record, and returns
    the best few.  It computes nothing and invents no evidence; the student still
    fills and confirms the worksheet.
    """
    words = set(_match_words(text))
    if not words:
        return {"matches": [], "none_reason": "Describe the case in a sentence or two and try again."}
    matches = []
    for catalogue_id, worksheet in WORKSHEETS.items():
        record = CATALOGUE.get(catalogue_id) or {}
        label = worksheet["label"]
        haystack = " ".join([label, worksheet["what"], record.get("summary", ""), record.get("name", "")]).lower()
        hits = sorted(word for word in words if word in haystack)
        if not hits:
            continue
        label_hits = sorted(word for word in words if word in label.lower())
        score = len(hits) + 2 * len(label_hits)
        matches.append({"catalogue_id": catalogue_id, "label": label, "template": worksheet["template"],
                        "score": score, "matched_terms": hits,
                        "why": "The description mentions " + ", ".join(hits) + "."})
    matches.sort(key=lambda item: (-item["score"], item["label"]))
    if not matches:
        return {"matches": [], "none_reason": "No worksheet matches that description yet. Choose one from the list, or open a blank worksheet."}
    return {"matches": matches[:limit], "none_reason": None}


def methods_for(subject_id):
    """Every frozen method id a subject page can launch (tools + worksheets)."""
    definition = _subject_definition(subject_id)
    methods = [TOOL_INFO[key]["method"] for key in definition["tools"]]
    methods.extend(WORKSHEETS[cid]["template"] for cid in definition["worksheets"])
    return methods


def filter_cases(summaries, subject_id):
    """Stored case summaries whose recorded method belongs to the subject.

    A corrupt summary has no method and is therefore not claimed by any
    subject; it stays visible on the case shelf instead.
    """
    methods = set(methods_for(subject_id))
    return [summary for summary in summaries
            if not summary.get("corrupt") and summary.get("method") in methods]


def compute_tools():
    """The deduplicated union of compute tools across the subjects.

    The Calculator's guard consumes this: one source of truth for the subject
    pages and the rail Calculator.
    """
    seen = set()
    tools = []
    for definition in SUBJECT_DEFS:
        for key in definition["tools"]:
            if key in seen:
                continue
            seen.add(key)
            tools.append(_tool(key))
    return tools


def calculator_groups():
    """The Calculator's tool groups, in business-function order."""
    groups = []
    for group in CALCULATOR_GROUPS:
        groups.append({
            "id": group["id"],
            "label": group["label"],
            "tools": [_tool(key) for key in group["tools"]],
        })
    return {"format": CALCULATOR_FORMAT, "groups": groups,
            "note": ("Every calculation is a frozen method run through the normal pipeline. "
                     "The Calculator arranges inputs and launches the method; it computes nothing. "
                     "Typed free-form arithmetic is not supported: it would be a second arithmetic path.")}


