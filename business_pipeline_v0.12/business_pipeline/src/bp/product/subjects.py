"""Subject index for the product layer (standard library only).

The owner's instruction is to change the product's organising idea from a
*run* to a *case* and to make the subjects of business the second entry point
(`docs/DISCUSSION_NOTEBOOK.md`, sections F/G, Option B).  This module is the
testable product-side catalogue behind that screen:

* it maps a **subject** (Accounting, Finance, Economics, Management, ...) to
  the tools the frozen engine can actually run today, and to the catalogue
  records it can only *structure* (T4) or read (no worksheet yet);
* it maps each launched id to the frozen preset/method/template it consumes;
* it names, for every subject, the registry records it owns, so the UI can
  show honest "catalogue only - no worksheet yet" rows;
* it groups the compute tools for the rail Calculator.

It computes **nothing**: every tool entry is a launcher descriptor.  The
numbers still come from `POST /api/sessions` -> `POST /api/sessions/{id}/confirm`
through the normal pipeline, and no product module imports the frozen core.

The data is generated once from the registry and the frozen preset list by
`scripts/generate_subjects.py`, then committed.  `tests/test_product_subjects.py`
re-reads `tests/fixtures/frozen_contract.json` and
`src/bp/data/registry_v0_2.json` as **data** and fails if any launch id or
catalogue id here disappears.  That is the house drift pattern: deterministic
bytes plus a guard, and no core import in this package.
"""

