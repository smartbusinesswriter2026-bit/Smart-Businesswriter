"""Dump the frozen contract for every economics tool's method (read-only).

Source of truth rank 1 for `qa/manual/economics.md`: `bp.methods.LIBRARY[id]`.

Usage:  python qa/probe_econ_contracts.py
Writes: qa/baseline/econ_contracts.md  (one block per method, manual-ready)
        qa/baseline/econ_contracts.json (machine-readable)
"""
import json
import pathlib
import sys

sys.path.insert(0, "src")

from bp import methods                      # noqa: E402
from bp.product import subjects             # noqa: E402

APP = pathlib.Path(__file__).resolve().parent.parent


def schema_rows(schema):
    rows = []
    for name in sorted(schema or {}):
        spec = schema[name]
        rows.append({
            "name": name,
            "type": spec.get("type"),
            "required": spec.get("required", True),
            "desc": spec.get("desc"),
            "choices": spec.get("choices"),
            "unit": spec.get("unit"),
            "default": spec.get("default"),
        })
    return rows


def main():
    detail = subjects.detail("economics")
    out = []
    lines = ["# Economics method contracts", "",
             "Generated by `qa/probe_econ_contracts.py` from `bp.methods.LIBRARY`.", ""]
    for tool in detail["tools"]:
        method = methods.LIBRARY[tool["method"]]
        record = {
            "tool": tool["key"],
            "label": tool["label"],
            "group": tool.get("group"),
            "level": tool.get("level"),
            "preset": tool["preset"],
            "method": tool["method"],
            "name": method.name,
            "tier": method.tier,
            "metric": method.metric,
            "unit": method.unit,
            "claim_ceiling": method.claim_ceiling,
            "output_precision": getattr(method, "output_precision", None),
            "output_units": getattr(method, "output_units", None),
            "test_names": list(method.test_names or ()),
            "intended_use": method.intended_use,
            "unsupported_use": method.unsupported_use,
            "assumptions": list(method.assumptions or ()),
            "limitations": list(method.limitations or ()),
            "inputs": schema_rows(method.input_schema),
            "defaults": getattr(method, "defaults", None),
        }
        out.append(record)

        lines.append("## %s — %s" % (tool["key"], tool["label"]))
        lines.append("")
        lines.append("- tool key: `%s` · preset: `%s` · method: `%s`"
                     % (tool["key"], tool["preset"], tool["method"]))
        lines.append("- group: %s · level: %s · tier: %s · unit: %s · ceiling: %s"
                     % (tool.get("group"), tool.get("level"), method.tier,
                        method.unit, method.claim_ceiling))
        lines.append("- metric: %s" % method.metric)
        lines.append("- claims: %s" % method.intended_use)
        lines.append("- refuses: %s" % method.unsupported_use)
        lines.append("- assumptions: %s" % "; ".join(method.assumptions or ()))
        lines.append("- limitations: %s" % "; ".join(method.limitations or ()))
        lines.append("- checks: %s" % ", ".join(method.test_names or ()))
        lines.append("")
        lines.append("| input | type | required | unit | notes |")
        lines.append("|---|---|---|---|---|")
        for row in record["inputs"]:
            notes = row["desc"] or ""
            if row["choices"]:
                notes += " (choices: %s)" % (", ".join(map(str, row["choices"])))
            lines.append("| `%s` | %s | %s | %s | %s |"
                         % (row["name"], row["type"], row["required"],
                            row["unit"] or "", notes.replace("|", "/")))
        lines.append("")

    (APP / "qa" / "baseline" / "econ_contracts.md").write_text(
        "\n".join(lines), encoding="utf-8")
    (APP / "qa" / "baseline" / "econ_contracts.json").write_text(
        json.dumps(out, indent=1, default=str), encoding="utf-8")
    print("wrote %d method contracts" % len(out))


if __name__ == "__main__":
    main()
