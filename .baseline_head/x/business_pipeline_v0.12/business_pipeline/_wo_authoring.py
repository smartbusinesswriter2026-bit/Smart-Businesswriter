"""WO-2a: the authored unit and voice for the 32 orphan profiles.

The 32 profiles were built from one template and inherited VRIO's unit and
voice verbatim: the unit said "VRIO evaluates resources against an industry's
competitors", the voice called the blocks "tests" and asked whether a resource
was valuable, rare, costly to imitate and organized to capture value.  That is
a framework substitution, and it would have been published as soon as the
profiles were registered.

This file is the authored replacement.  Each entry says, in the framework's own
terms, what the unit of analysis is and how the prose should speak about it.

`field` is the unit's field in `bp.product.completion`:

- ``industry``  the evidence is about a market.  The engine detects the market
  from the brief and runs the industry fit guard.
- ``process``   the evidence is about something the student names: a change
  programme, an organisation, a process.  The engine never detects one and
  refuses to guess.

The `process` profiles carry the house convention that goes with the field:
``sites`` None, ``providers`` None and the retrieval gate that does not demand
a title cue or a title context.
"""

