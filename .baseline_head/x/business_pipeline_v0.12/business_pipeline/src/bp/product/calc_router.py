"""Deterministic sentence -> calculator plan router (product layer, stdlib only).

The Business Calculator's chat is not a second engine: a typed sentence is
parsed here into a **draft plan** naming one frozen tool and the figures the
sentence actually stated.  The browser shows the plan, the user confirms it,
and the normal `POST /api/sessions` -> `POST /api/sessions/{id}/confirm`
pair runs the method.  This module therefore computes **nothing** and imports
no frozen core module; it reads a committed slice of the method input schemas
(`data/calc_inputs_v0_1.json`, regenerated by `scripts/generate_calc_inputs.py`).

Five declared outcomes (see `docs/proposals/BUSINESS_CALCULATOR_DESIGN.md` §5):

    run           one clear tool, every declared input read from the sentence
    need_inputs   one clear tool, at least one declared input missing
    choose        two or three plausible tools; the user picks
    unsupported   business, but no frozen method exists (tax, market data)
    out_of_scope  not a business computation at all

House rules this module keeps: a missing figure is never defaulted, a method
is never invented, a percentage is never silently converted, and the message
is data - never an instruction.
"""

